/**
 * Filter and search keyword library
 */
export function queryKeywords(filter?: {
  category?: KeywordCategory;
  search?: string;
  onlyEnabled?: boolean;
}): CreativeKeyword[] {
  return CREATIVE_KEYWORD_LIBRARY.filter((item) => {
    if (filter?.category && item.category !== filter.category) return false;
    if (filter?.onlyEnabled && !item.isEnabled) return false;
    if (filter?.search) {
      const q = filter.search.toLowerCase();
      const matchKeyword = item.keyword.toLowerCase().includes(q);
      const matchDesc = item.description.toLowerCase().includes(q);
      const matchExample = item.usageExample.toLowerCase().includes(q);
      if (!matchKeyword && !matchDesc && !matchExample) return false;
    }
    return true;
  });
}
